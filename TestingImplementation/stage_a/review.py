from pathlib import Path
import yaml

def existing_review_matches(partial: dict, review_dir: Path) -> bool:
    fingerprint = partial.get('_input_fingerprint')
    if not fingerprint:
        return False
    review_path = review_dir / f'{partial['attack_id']}_review.yaml'
    if not review_path.exists():
        return False
    try:
        record = yaml.safe_load(review_path.read_text(encoding='utf-8')) or {}
    except (OSError, yaml.YAMLError):
        return False
    spec = record.get('enriched_spec') or {}
    provenance = spec.get('source_provenance') or {}
    old_fingerprint = provenance.get('authorization_profile_fingerprint')
    if old_fingerprint:
        return old_fingerprint == fingerprint
    analysis = spec.get('spec_analysis') or {}
    return analysis.get('endpoint_id') == partial.get('_endpoint_id') and analysis.get('case_id') == partial.get('_case_id')

def write_review_file(enriched: dict, review_dir: Path) -> Path:
    review_dir.mkdir(parents=True, exist_ok=True)
    attack_id = enriched['spec']['attack_id']
    review_path = review_dir / f'{attack_id}_review.yaml'
    record = {'approved': False, 'reviewer_notes': '', 'needs_review': enriched['needs_review'], 'review_reasons': enriched['review_reasons'], 'enriched_spec': enriched['spec'], 'field_annotations': enriched['annotations']}
    with open(review_path, 'w', encoding='utf-8') as f:
        f.write('# Review file generated by Stage A — Spec Enrichment\n')
        f.write('#\n')
        f.write('# Instructions:\n')
        f.write('#   1. Check fields with review: true in field_annotations\n')
        f.write('#   2. Correct enriched_spec where needed\n')
        f.write('#   3. Set approved: true and add reviewer_notes\n')
        f.write('#   4. Re-run: python stage_a/stage_a.py --finalize\n')
        f.write('#\n')
        yaml.dump(record, f, allow_unicode=True, default_flow_style=False, sort_keys=False, width=120)
    return review_path

def load_approved_reviews(review_dir: Path) -> list[dict]:
    approved = []
    for review_file in sorted(review_dir.glob('*_review.yaml')):
        with open(review_file, encoding='utf-8') as f:
            record = yaml.safe_load(f)
        if record and record.get('approved', False):
            approved.append(record)
    return approved
